import shutil, subprocess, os, glob
SRC='/home/chris/wt-T0134/posts'; DST='/home/chris/wt-T0134/build-verify/drv/mutposts'
def reset():
    for f in glob.glob(DST+'/*.pp'): os.remove(f)
    for f in glob.glob(SRC+'/*.pp'): shutil.copy(f, DST)
def run():
    r=subprocess.run(['./pst','T-0134: shipped posts follow*'],capture_output=True,text=True)
    return r.returncode
muts=[
 ('grbl_mm','(Tool [T]: [TOOLNAME])','(Tool [T]: [TOOLNAME]OPEN)',1),
 ('linuxcnc_mm','([TP_FILENAME])','([TP_FILENAME],x)',1),
 ('marlin_mm','; [TP_FILENAME]"','; [TP_FILENAME] x"',1),
 ('mach3_mm','([TP_FILENAME])','([TP_FILENAME][T])',1),
 ('grbl_mm','([TP_FILENAME])','([TP_FILENAME]\t)',1),
 ('mach4_mm','(Generated by [PRODUCT])','(Generated by [PRODUCT]CLOSE)',1),
 ('linuxcnc_inch','"([TP_FILENAME])"','   "([TP_FILENAME]OPEN)"   ',1),
 ('grbl_inch','"([TP_FILENAME])"\n','"([TP_FILENAME])"\n"(x [TOOL_NOTES]OPEN)"\n',1),
 ('mach3_inch','"([TP_FILENAME])"\n','"([TP_FILENAME])"\n"(x [CUTTER_COMP],)"\n',1),
 ('linuxcnc_mm','"([TP_FILENAME])"','"([TP_FILENAME][TOOLNAME])"',0),
 ('linuxcnc_mm','"([TP_FILENAME])"','"([TP_FILENAME][TOOLNAME])"',1,'VAR PN = [TOOLNAME|A|OPEN|1.0]\n'),
 ('grbl_mm','"([TP_FILENAME])"','"([TP_FILENAME]) LOG"',0),
 ('grbl_mm','(Tool [T]: [TOOLNAME])','(Tool [T]: [toolname]OPEN)',None),
]
for m in muts:
    reset(); stem,a,b,expect=m[:4]; pre=m[4] if len(m)>4 else ''
    p=f'{DST}/{stem}.pp'; s=open(p,newline='').read()
    assert a in s,(stem,a)
    s=pre+s.replace(a,b,1); open(p,'w',newline='').write(s)
    rc=run(); print(('FLAGGED' if rc else 'passes '), 'expect', expect, stem, repr(b))
# CRLF variant
reset(); p=DST+'/grbl_mm.pp'; s=open(p,newline='').read().replace('(Tool [T]: [TOOLNAME])','(Tool [T]: [TOOLNAME]OPEN)').replace('\n','\r\n'); open(p,'w',newline='').write(s); print('CRLF', 'FLAGGED' if run() else 'passes')
# no trailing newline, mutation on last line
reset(); p=DST+'/grbl_mm.pp'; s=open(p,newline='').read().rstrip('\n')+'\nbegin FOOTER2\n"([TOOLNAME]OPEN)"'; open(p,'w',newline='').write(s); print('lastline-nonl', 'FLAGGED' if run() else 'passes')
reset(); print('clean', 'FLAGGED' if run() else 'passes')
